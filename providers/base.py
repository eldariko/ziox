"""Base Twitter Provider interface and data models."""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import List, Optional, Dict, Any


class ScannerCircuitBreakerError(Exception):
    """
    Raised when the X scanner encounters a rate-limit (429), authentication failure (401/403),
    or account challenge/lock (e.g. code 326 / Arkose captcha) that puts the scanning profile at risk.
    """

    def __init__(self, message: str, status_code: Optional[int] = None, reason: str = "ACCOUNT_RISK"):
        super().__init__(message)
        self.status_code = status_code
        self.reason = reason


def classify_scanner_exception(exc: Exception) -> Optional[ScannerCircuitBreakerError]:
    """
    Inspect an exception raised during X scanning (e.g. from Twikit or HTTP client).
    If it represents an account risk (HTTP 401, 403, 429, AccountLocked, Unauthorized, RateLimit),
    return a ScannerCircuitBreakerError; otherwise return None.
    """
    if isinstance(exc, ScannerCircuitBreakerError):
        return exc

    exc_type = type(exc).__name__.lower()
    err_msg = str(exc)
    err_lower = err_msg.lower()
    status_code = getattr(exc, "status_code", None) or getattr(exc, "status", None)

    # 1. Rate Limit Detection (HTTP 429 / TooManyRequests)
    if (
        status_code == 429
        or "toomanyrequests" in exc_type
        or "ratelimit" in exc_type
        or "429" in err_lower
        or "rate limit" in err_lower
        or "too many requests" in err_lower
    ):
        return ScannerCircuitBreakerError(
            f"X Rate Limit triggered (HTTP 429): {err_msg}",
            status_code=429,
            reason="RATE_LIMIT_429",
        )

    # 2. Account Lock / Challenge / Suspension Detection (Code 326 / Arkose / Locked)
    if (
        "accountlocked" in exc_type
        or "accountsuspended" in exc_type
        or "326" in err_lower
        or "locked" in err_lower
        or "arkose" in err_lower
        or "challenge" in err_lower
        or "suspended" in err_lower
    ):
        return ScannerCircuitBreakerError(
            f"X Account Lock or Challenge detected: {err_msg}",
            status_code=status_code or 403,
            reason="ACCOUNT_LOCKED_OR_CHALLENGE",
        )

    # 3. Authentication / Session Invalidation Detection (HTTP 401 / 403)
    if (
        status_code in (401, 403)
        or "unauthorized" in exc_type
        or "forbidden" in exc_type
        or "401" in err_lower
        or "403" in err_lower
        or "could not authenticate you" in err_lower
    ):
        code = status_code if status_code in (401, 403) else (401 if "401" in err_lower else 403)
        return ScannerCircuitBreakerError(
            f"X Session Authentication / Forbidden error (HTTP {code}): {err_msg}",
            status_code=code,
            reason=f"AUTH_FAILURE_{code}",
        )

    return None


@dataclass
class Tweet:
    """Represents a Tweet retrieved from X or generated by a provider."""
    id: str
    text: str
    author_handle: str
    created_at: datetime
    likes: int = 0
    retweets: int = 0
    replies: int = 0
    conversation_id: Optional[str] = None
    in_reply_to_tweet_id: Optional[str] = None
    raw_data: Dict[str, Any] = field(default_factory=dict)

    @property
    def age_in_minutes(self) -> float:
        """Calculate tweet age in minutes relative to UTC now."""
        now = datetime.now(timezone.utc)
        tweet_time = self.created_at
        if tweet_time.tzinfo is None:
            tweet_time = tweet_time.replace(tzinfo=timezone.utc)
        delta_seconds = max(0.0, (now - tweet_time).total_seconds())
        return delta_seconds / 60.0


class BaseTwitterProvider(ABC):
    """Abstract interface for Twitter/X integration."""

    @abstractmethod
    def search_recent_tweets(self, query: str, limit: int = 10) -> List[Tweet]:
        """Search recent tweets matching query."""
        pass

    @abstractmethod
    def post_reply(
        self,
        text: str,
        reply_to_tweet_id: str,
        media_paths: Optional[List[str]] = None
    ) -> Dict[str, Any]:
        """Post a reply tweet."""
        pass

    @abstractmethod
    def get_tweet(self, tweet_id: str) -> Optional[Tweet]:
        """Fetch a specific tweet by ID."""
        pass
